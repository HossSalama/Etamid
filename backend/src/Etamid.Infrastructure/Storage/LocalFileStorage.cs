using Etamid.Application.Common.Interfaces;
using Microsoft.Extensions.Configuration;
using Microsoft.Extensions.Hosting;

namespace Etamid.Infrastructure.Storage;

/// <summary>Development / single-server storage on disk. Replace with an object-storage implementation for production scale.</summary>
public sealed class LocalFileStorage(IConfiguration configuration, IHostEnvironment environment) : IFileStorage
{
    public static string ResolveRoot(IConfiguration configuration, IHostEnvironment environment)
    {
        var configured = configuration["Storage:LocalPath"];
        return string.IsNullOrWhiteSpace(configured)
            ? Path.Combine(environment.ContentRootPath, "storage")
            : Path.GetFullPath(configured);
    }

    public async Task SaveAsync(string key, Stream content, CancellationToken cancellationToken)
    {
        var root = ResolveRoot(configuration, environment);
        var fullPath = Path.GetFullPath(Path.Combine(root, key.Replace('/', Path.DirectorySeparatorChar)));

        // Keys are generated by the application; this is a second line of defence against path traversal.
        if (!fullPath.StartsWith(root, StringComparison.OrdinalIgnoreCase))
            throw new InvalidOperationException("Invalid storage key.");

        Directory.CreateDirectory(Path.GetDirectoryName(fullPath)!);
        await using var target = File.Create(fullPath);
        await content.CopyToAsync(target, cancellationToken);
    }
}
